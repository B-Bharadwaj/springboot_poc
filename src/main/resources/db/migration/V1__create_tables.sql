-- Naming rule: Hibernate maps camelCase Java fields to snake_case columns
-- (createdAt -> created_at, unitPrice -> unit_price), and @ManyToOne fields use their
-- @JoinColumn name (user_id, order_id, product_id). Table names come from @Table.
-- Column names and types here must match the entities, or ddl-auto=validate fails at startup.

CREATE TABLE users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL
);

CREATE TABLE products (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255)     NOT NULL,
    price    DOUBLE PRECISION NOT NULL,
    quantity INTEGER          NOT NULL
);

CREATE TABLE orders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id),
    status     VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT           NOT NULL REFERENCES orders (id),
    product_id BIGINT           NOT NULL REFERENCES products (id),
    quantity   INTEGER          NOT NULL,
    unit_price DOUBLE PRECISION NOT NULL
);
